"""Builds the retrieval benchmark: for each query, which knowledge-base topics are relevant.

Labels are produced by a model that sees the query and the full list of topic titles, never any retriever's output,
so they don't favor one retrieval method. They are "silver" labels: LLM-generated, spot-checked by the developer,
not reviewed by a clinician. The search query each retriever receives (the person's words plus a medical-term
rewrite, exactly as the app builds it) is generated once and stored, so every retriever gets identical input.

Usage (from the doctor/ folder):  python evaluation/build_retrieval_benchmark.py
Writes evaluation/datasets/retrieval_benchmark.json.
"""
import json
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))
from evaluation.datasets.retrieval_queries import QUERIES  # noqa: E402
from medi import config, llm  # noqa: E402
from medi.rag.retrieval import rewrite_query  # noqa: E402

LABEL_MODEL = config.MODEL
SCHEMA = {
    "name": "relevance",
    "strict": True,
    "schema": {
        "type": "object", "additionalProperties": False, "required": ["primary", "related"],
        "properties": {"primary": {"type": "array", "items": {"type": "string"}},
                       "related": {"type": "array", "items": {"type": "string"}}},
    },
}
PROMPT = """You label a retrieval benchmark for a health information assistant. The knowledge base has one entry per topic;
the full list of topic titles is below. For the person's message, choose:
- "primary": the 1-3 topics whose content most directly answers or explains it (the topics a careful clinician would
  open first). For symptoms, choose the most likely condition(s) and, if it matters for safety, the dangerous one to rule out.
- "related": up to 5 other topics that would also be genuinely useful (symptom topics, tests, treatments, closely related
  conditions). Leave out loosely related topics.
Copy titles exactly from the list. Only choose titles that appear in the list.

TOPIC TITLES:
{titles}"""


def label(query, titles, title_set):
    out = json.loads(llm.chat_text({
        "model": LABEL_MODEL,
        "temperature": 0,
        "messages": [{"role": "system", "content": PROMPT.format(titles="\n".join(titles))},
                     {"role": "user", "content": query["text"]}],
        "response_format": {"type": "json_schema", "json_schema": SCHEMA},
    }, timeout=120, retries=6))
    primary = [t for t in out["primary"] if t in title_set]
    related = [t for t in out["related"] if t in title_set and t not in primary]
    return primary, related


def main():
    sources = json.loads((HERE.parent / "rag" / "sources.json").read_text(encoding="utf-8"))
    titles = sorted({d["title"] for d in sources["documents"]})
    title_set = set(titles)

    path = HERE / "datasets" / "retrieval_benchmark.json"
    existing = {q["qid"]: q for q in json.loads(path.read_text(encoding="utf-8"))["queries"]} if path.exists() else {}

    def build(q):
        if q["qid"] in existing and existing[q["qid"]]["text"] == q["text"]:
            return existing[q["qid"]]
        primary, related = label(q, titles, title_set) if q["kind"] != "out_of_scope" else ([], [])
        rewrite = rewrite_query(q["text"]) if q["mode"] == "health" else ""
        search = f"{q['text']}\n{rewrite}" if rewrite else q["text"]
        return {**q, "search_query": search, "primary": primary, "related": related}

    with ThreadPoolExecutor(max_workers=3) as pool:
        rows = list(pool.map(build, QUERIES))
    empty = [r["qid"] for r in rows if not r["primary"] and r["kind"] != "out_of_scope"]
    previous = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    out = {
        **{k: v for k, v in previous.items() if k == "adjudicated"},
        "dataset": "medi-retrieval-r1",
        "created": time.strftime("%Y-%m-%d"),
        "label_model": LABEL_MODEL,
        "rewrite_model": config.FAST_MODEL,
        "knowledge_base_snapshot": sources.get("medlineplus_date_generated"),
        "note": "Silver labels: generated by an LLM from the topic list without seeing retriever output, spot-checked "
                "by the developer, not clinician-reviewed. Queries are synthetic.",
        "queries": rows,
    }
    path.write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"{len(rows)} queries labeled; {len(empty)} with no primary topic: {empty}")


if __name__ == "__main__":
    main()
